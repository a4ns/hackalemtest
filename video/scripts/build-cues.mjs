// cues.json (+ the brand mark grid) → config/cues.js, an ES module that both the page and the audio scripts read.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const cues = JSON.parse(fs.readFileSync(path.join(root, "config/cues.json"), "utf8"));
cues.markGrid = JSON.parse(fs.readFileSync(path.join(root, "assets/brand/mark_grid.json"), "utf8")).map((r) => (typeof r === "string" ? r : r.map((v) => (v ? "#" : ".")).join("")));
fs.writeFileSync(path.join(root, "config/cues.js"), "// generated by scripts/build-cues.mjs from config/cues.json — do not edit by hand\nexport default " + JSON.stringify(cues, null, 1) + ";\n");
console.log("cues.js written; mark cells:", cues.markGrid.join("").split("#").length - 1);
